import { describe, it, expect } from 'vitest'
import { getLanguageFromFileName } from '@/utils/languageMap'

describe('getLanguageFromFileName', () => {
  it('.ts -> typescript', () => expect(getLanguageFromFileName('app.ts')).toBe('typescript'))
  it('.tsx -> typescript', () => expect(getLanguageFromFileName('app.tsx')).toBe('typescript'))
  it('.js -> javascript', () => expect(getLanguageFromFileName('app.js')).toBe('javascript'))
  it('.jsx -> javascript', () => expect(getLanguageFromFileName('app.jsx')).toBe('javascript'))
  it('.vue -> html', () => expect(getLanguageFromFileName('App.vue')).toBe('html'))
  it('.rs -> rust', () => expect(getLanguageFromFileName('main.rs')).toBe('rust'))
  it('.py -> python', () => expect(getLanguageFromFileName('script.py')).toBe('python'))
  it('.css -> css', () => expect(getLanguageFromFileName('style.css')).toBe('css'))
  it('.scss -> scss', () => expect(getLanguageFromFileName('style.scss')).toBe('scss'))
  it('.less -> less', () => expect(getLanguageFromFileName('style.less')).toBe('less'))
  it('.json -> json', () => expect(getLanguageFromFileName('package.json')).toBe('json'))
  it('.xml -> xml', () => expect(getLanguageFromFileName('config.xml')).toBe('xml'))
  it('.yaml -> yaml', () => expect(getLanguageFromFileName('config.yaml')).toBe('yaml'))
  it('.yml -> yaml', () => expect(getLanguageFromFileName('config.yml')).toBe('yaml'))
  it('.toml -> toml', () => expect(getLanguageFromFileName('Cargo.toml')).toBe('toml'))
  it('.md -> markdown', () => expect(getLanguageFromFileName('readme.md')).toBe('markdown'))
  it('.mdx -> markdown', () => expect(getLanguageFromFileName('docs.mdx')).toBe('markdown'))
  it('.sql -> sql', () => expect(getLanguageFromFileName('query.sql')).toBe('sql'))
  it('.sh -> bash', () => expect(getLanguageFromFileName('script.sh')).toBe('bash'))
  it('.bat -> bash', () => expect(getLanguageFromFileName('script.bat')).toBe('bash'))
  it('.ps1 -> powershell', () => expect(getLanguageFromFileName('script.ps1')).toBe('powershell'))
  it('.c -> c', () => expect(getLanguageFromFileName('main.c')).toBe('c'))
  it('.cpp -> cpp', () => expect(getLanguageFromFileName('main.cpp')).toBe('cpp'))
  it('.h -> c', () => expect(getLanguageFromFileName('header.h')).toBe('c'))
  it('.hpp -> cpp', () => expect(getLanguageFromFileName('header.hpp')).toBe('cpp'))
  it('.java -> java', () => expect(getLanguageFromFileName('Main.java')).toBe('java'))
  it('.go -> go', () => expect(getLanguageFromFileName('main.go')).toBe('go'))
  it('.rb -> ruby', () => expect(getLanguageFromFileName('script.rb')).toBe('ruby'))
  it('.php -> php', () => expect(getLanguageFromFileName('index.php')).toBe('php'))
  it('.swift -> swift', () => expect(getLanguageFromFileName('main.swift')).toBe('swift'))
  it('.kt -> kotlin', () => expect(getLanguageFromFileName('main.kt')).toBe('kotlin'))
  it('.dart -> dart', () => expect(getLanguageFromFileName('main.dart')).toBe('dart'))
  it('.lua -> lua', () => expect(getLanguageFromFileName('script.lua')).toBe('lua'))
  it('.r -> r', () => expect(getLanguageFromFileName('script.r')).toBe('r'))
  it('.ini -> ini', () => expect(getLanguageFromFileName('config.ini')).toBe('ini'))
  it('.cfg -> ini', () => expect(getLanguageFromFileName('config.cfg')).toBe('ini'))
  it('.conf -> ini', () => expect(getLanguageFromFileName('config.conf')).toBe('ini'))
  it('.env -> ini', () => expect(getLanguageFromFileName('.env')).toBe('ini'))
  it('.gitignore -> gitignore', () => expect(getLanguageFromFileName('.gitignore')).toBe('gitignore'))
  it('.html -> html', () => expect(getLanguageFromFileName('index.html')).toBe('html'))
  it('.htm -> html', () => expect(getLanguageFromFileName('index.htm')).toBe('html'))
  it('.txt -> text', () => expect(getLanguageFromFileName('notes.txt')).toBe('text'))
  it('unknown ext -> text', () => expect(getLanguageFromFileName('file.xyz')).toBe('text'))
  it('no ext -> text', () => expect(getLanguageFromFileName('README')).toBe('text'))
  it('uppercase .TS -> typescript', () => expect(getLanguageFromFileName('app.TS')).toBe('typescript'))
  it('mixed case .Md -> markdown', () => expect(getLanguageFromFileName('notes.Md')).toBe('markdown'))
})
